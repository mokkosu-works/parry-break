/// 入力イベントの時刻 (実時間) をシミュレーション時刻へ換算する。
///
/// 毎フレームの終わりに「その時点の実時間とシミュレーション時刻」を記録しておき、
/// 次のフレームで届いた入力の時刻を、記録からの経過時間 × 時間の倍率で換算する。
/// これによりパリィの判定はフレーム単位に丸められず、押した瞬間の時刻で行われる。
class TimeSync {
  double wall = 0, sim = 0;

  /// 実時間 1 秒あたりに進むシミュレーション時間 (スローモーション中は 0.35)。
  double scale = 1;

  double toSim(double wallTime) => sim + (wallTime - wall) * scale;
}
